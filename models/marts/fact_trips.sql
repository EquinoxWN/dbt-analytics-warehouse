-- Trip fact: one row per valid, de-duplicated green taxi trip, keyed to dim_date and dim_zone.
select
    trip_id,
    cast(strftime(pickup_date, '%Y%m%d') as integer) as pickup_date_key,
    pickup_location_id as pickup_zone_key,
    dropoff_location_id as dropoff_zone_key,
    pickup_at,
    dropoff_at,
    cast(pickup_hour as integer) as pickup_hour,
    vendor_name,
    rate_code_name,
    payment_type_name,
    trip_type_name,
    is_store_and_forward,
    is_airport_trip,
    passenger_count,
    trip_distance_miles,
    trip_duration_minutes,
    average_speed_mph,
    fare_amount,
    extra_amount,
    mta_tax_amount,
    tip_amount,
    tolls_amount,
    improvement_surcharge_amount,
    congestion_surcharge_amount,
    total_amount,
    source_file
from {{ ref('int_green_trips__enriched') }}
